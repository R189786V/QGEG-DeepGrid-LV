"""Build a SYNTHETIC, representative Zimbabwean urban (high-density suburb) LV feeder.

This is NOT a real ZETDC network. Equipment and conductor values are typical,
approximate figures. All customers, loads and daily profiles are synthetic.
Rooftop PV and batteries are added later in the DER phase.
"""
import math
import random
from pathlib import Path

random.seed(7)  # same network every time
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "opendss" / "zimbabwe_urban"
OUT.mkdir(parents=True, exist_ok=True)

SPAN = 35.0  # metres between poles
coords = {"sourcebus": (0.0, 30.0), "lv_board": (0.0, 0.0)}
lines, loads = [], []
count = {"line": 0, "house": 0}


def add_line(bus1, bus2, code, length, phases=3):
    count["line"] += 1
    lines.append(f"New Line.L{count['line']:03d} bus1={bus1} bus2={bus2} "
                 f"phases={phases} linecode={code} length={length:.1f} units=m")


def backbone(prefix, start, n_poles, angle_deg, code):
    x0, y0 = coords[start]
    a = math.radians(angle_deg)
    prev, poles = start, []
    for k in range(1, n_poles + 1):
        bus = f"{prefix}_{k:02d}"
        coords[bus] = (x0 + k * SPAN * math.cos(a), y0 + k * SPAN * math.sin(a))
        add_line(prev, bus, code, SPAN)
        poles.append(bus)
        prev = bus
    return poles


def add_1ph(pole, name, kw, shape):
    ph = random.choices(["1", "2", "3"], weights=[0.36, 0.33, 0.31])[0]
    px, py = coords[pole]
    a, d = random.uniform(0, 2 * math.pi), random.uniform(10, 20)
    coords[name] = (px + d * math.cos(a), py + d * math.sin(a))
    add_line(f"{pole}.{ph}", f"{name}.{ph}", "svc_16", d, phases=1)
    loads.append(f"New Load.{name} bus1={name}.{ph} phases=1 kv=0.23 kw={kw} "
                 f"pf=0.95 model=1 daily={shape}")


def add_house(pole):
    count["house"] += 1
    add_1ph(pole, f"h{count['house']:03d}", round(random.uniform(1.2, 2.8), 2),
            random.choice(["urban_a", "urban_b", "urban_c"]))


def add_3ph(pole, name, kw, pf, shape):
    px, py = coords[pole]
    coords[name] = (px + 20.0, py)
    add_line(pole, name, "abc_50", 20.0)
    loads.append(f"New Load.{name} bus1={name} phases=3 kv=0.4 kw={kw} "
                 f"pf={pf} model=1 daily={shape}")


# Feeders 1-3: residential streets, 4 houses per pole on poles 2-10
for k, angle in zip([1, 2, 3], [0, 90, 180]):
    for p in backbone(f"f{k}", "lv_board", 10, angle, "abc_95")[1:]:
        for _ in range(4):
            add_house(p)

# Feeder 4: shops, a school, then houses
f4 = backbone("f4", "lv_board", 10, 270, "abc_95")
for i, p in enumerate(["f4_02", "f4_03", "f4_04"], start=1):
    add_1ph(p, f"shop{i}", 3.0, "shop")
add_3ph("f4_06", "school", 10.0, 0.90, "school")
for p in f4[6:]:
    for _ in range(4):
        add_house(p)

shapes = {
    "urban_a": [0.3, 0.25, 0.25, 0.25, 0.4, 0.8, 1.0, 0.8, 0.45, 0.35, 0.3, 0.3,
                0.35, 0.3, 0.3, 0.35, 0.5, 0.75, 0.95, 0.9, 0.75, 0.6, 0.45, 0.35],
    "urban_b": [0.3, 0.25, 0.2, 0.2, 0.25, 0.5, 0.7, 0.6, 0.35, 0.3, 0.3, 0.3,
                0.35, 0.3, 0.3, 0.35, 0.55, 0.85, 1.0, 1.0, 0.85, 0.65, 0.5, 0.35],
    "urban_c": [0.25, 0.2, 0.2, 0.2, 0.3, 0.55, 0.7, 0.65, 0.6, 0.65, 0.7, 0.75,
                0.75, 0.7, 0.65, 0.6, 0.65, 0.8, 0.95, 1.0, 0.85, 0.6, 0.4, 0.3],
    "shop": [0.15] * 6 + [0.3, 0.6, 0.85, 0.9, 0.95, 1.0, 1.0, 0.95, 0.9, 0.9,
                          0.85, 0.8, 0.6, 0.3] + [0.15] * 4,
    "school": [0.1] * 7 + [0.6, 1, 1, 1, 1, 0.9, 0.8, 0.6, 0.3] + [0.1] * 8,
}

linecodes = """! Approximate values for aluminium ABC (aerial bundled conductor)
New LineCode.abc_95 nphases=3 r1=0.41 x1=0.08 r0=1.64 x0=0.32 units=km normamps=200
New LineCode.abc_50 nphases=3 r1=0.82 x1=0.09 r0=3.28 x0=0.36 units=km normamps=140
New LineCode.svc_16 nphases=1 rmatrix=[3.82] xmatrix=[0.20] cmatrix=[0] units=km normamps=75
"""

master = """! SYNTHETIC representative Zimbabwean urban LV feeder.
! NOT a real ZETDC network. See README.md in this folder.
Clear
New Circuit.zim_urban basekv=11 pu=1.0 phases=3 bus1=sourcebus MVAsc3=150 MVAsc1=120
Redirect LineCodes.dss
Redirect LoadShapes.dss
New Transformer.TX1 phases=3 windings=2 buses=[sourcebus lv_board] conns=[delta wye] kvs=[11 0.42] kvas=[315 315] %r=1.0 xhl=4.0
Redirect Lines.dss
Redirect Loads.dss
Set voltagebases=[11 0.4]
Calcvoltagebases
Buscoords Buscoords.txt
Set mode=snapshot
Solve
"""

readme = """# Zimbabwe urban LV feeder (synthetic)

This is a SYNTHETIC, representative high-density suburb network. It is not a
real ZETDC feeder. It was generated by src/build_zim_urban.py with a fixed seed.

- Supply: 11 kV, 315 kVA 11/0.42 kV Dyn transformer
- F1-F3 Residential: 350 m 95 mm2 ABC each, 36 houses per street
- F4 Mixed: 3 shops, a 10 kW school, 16 houses
- Conductor and transformer parameters are approximate typical values
- Daily load profiles are synthetic hourly shapes, not measured data
- Rooftop PV and home batteries are added in the DER phase
"""


def write(name, text):
    (OUT / name).write_text(text, encoding="utf-8")


write("Master.dss", master)
write("LineCodes.dss", linecodes)
write("Lines.dss", "\n".join(lines) + "\n")
write("Loads.dss", "\n".join(loads) + "\n")
write("LoadShapes.dss", "\n".join(
    f"New Loadshape.{k} npts=24 interval=1 mult=({' '.join(str(v) for v in vals)})"
    for k, vals in shapes.items()) + "\n")
write("Buscoords.txt", "\n".join(f"{b}, {x:.1f}, {y:.1f}" for b, (x, y) in coords.items()) + "\n")
write("README.md", readme)

print(f"Built {len(lines)} lines, {len(loads)} loads, {count['house']} houses")
print(f"Files written to {OUT}")
